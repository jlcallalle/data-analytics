"""---
## 04 · PMF y CDF: programando la fórmula

**Regla de la casa:** una fórmula que no puedes programar, no la entiendes de verdad.

Vamos a escribir la Binomial con nuestras propias manos y después comprobar que da lo mismo que
la versión oficial de `scipy`. La fórmula, la misma de la slide 7:

$$P(X = k) = \binom{n}{k}\, p^{k} (1-p)^{n-k}$$

Donde:
- $\binom{n}{k}$ (que en el código escribimos `comb(n, k)`) = de cuántas formas puede pasar
- $p^{k}$ = la chance de que los k que sí, sí
- $(1-p)^{n-k}$ = la chance de que los otros n−k fallen

> **Analogía — velocímetro y odómetro.** La PMF es el velocímetro: el valor exacto en este punto.
> La CDF es el odómetro: todo lo acumulado hasta aquí, y nunca baja.
"""

from math import comb          # comb(n, k) calcula las combinaciones. Ya viene con Python.

# ── Definimos nuestra propia función ─────────────────────────────────────────
# "def" significa "define una función". Una función es una receta a la que le pasas
# ingredientes (k, n, p) y te devuelve un resultado.
def binomial_pmf(k, n, p):
    '''Calcula P(X = k) para una Binomial(n, p), tal cual la fórmula.'''
    return comb(n, k) * p**k * (1 - p)**(n - k)
    #      ^^^^^^^^^^   ^^^^^   ^^^^^^^^^^^^^^^^
    #      pedazo 1     pedazo 2      pedazo 3      (** significa "elevado a")

n, p = 30, 0.30                # 30 intentos, 30% de chance cada uno
ks = np.arange(0, n + 1)       # ks = [0, 1, 2, ..., 30], todos los resultados posibles

# Calculamos la PMF de dos maneras y comparamos
pmf_mano  = np.array([binomial_pmf(k, n, p) for k in ks])   # con NUESTRA función
pmf_scipy = stats.binom.pmf(ks, n, p)                        # con la versión oficial

# np.allclose pregunta: "¿son iguales estos dos conjuntos de números?"
print("¿Nuestra fórmula da lo mismo que scipy?", np.allclose(pmf_mano, pmf_scipy))
print("Suma de todas las probabilidades:", pmf_mano.sum().round(10), " <- tiene que ser 1")

"""Que la suma dé exactamente 1 no es un detalle: es tu **primer chequeo siempre**. Si no da 1,
hay un error en algún lado.
"""

cdf_scipy = stats.binom.cdf(ks, n, p)      # la acumulada, ya lista en scipy

# plt.subplots(1, 2) crea dos gráficos lado a lado. axes[0] es el izquierdo, axes[1] el derecho.
fig, axes = plt.subplots(1, 2, figsize=(12, 4.2))

axes[0].bar(ks, pmf_scipy, color=AZUL, alpha=0.85, edgecolor="white")
axes[0].axvline(n * p, color=ROSA, ls="--", lw=2, label=f"E[X] = n×p = {n*p:.0f}")
axes[0].set_title(f"PMF · P(X = k) · Binomial(n={n}, p={p})")
axes[0].set_xlabel("k (cuántos éxitos)")
axes[0].legend()

# .step dibuja escalones en vez de una línea suave. Es lo correcto para una CDF discreta:
# la probabilidad salta de golpe en cada valor entero, no sube en diagonal.
axes[1].step(ks, cdf_scipy, where="post", color=ROSA, lw=2.5)
axes[1].set_title("CDF · P(X ≤ k) · acumulada")
axes[1].set_xlabel("k")
axes[1].set_ylim(0, 1.05)

plt.tight_layout()             # acomoda los dos gráficos para que no se pisen
plt.show()

"""### El error del ±1: el bug número uno

Quieres saber `P(X ≥ 12)`, o sea "12 o más". La tentación es escribir `1 - cdf(12)`.

**Está mal.** Y la razón es simple: `cdf(12)` ya incluye al 12. Si le restas eso a 1, estás
quitando también al 12, y el 12 **sí** cuenta. Lo correcto es `1 - cdf(11)`.

Vamos a comprobarlo de cuatro formas distintas.
"""

k0 = 12

mal     = 1 - stats.binom.cdf(k0, n, p)        # esto en realidad es P(X ≥ 13)
bien    = 1 - stats.binom.cdf(k0 - 1, n, p)    # esto sí es P(X ≥ 12)
directo = stats.binom.sf(k0 - 1, n, p)         # sf = "survival function" = 1 − cdf, ya hecha
fuerza  = pmf_scipy[ks >= k0].sum()            # sumar a mano todas las probabilidades de 12 en adelante

print(f"1 − cdf(12)             = {mal:.6f}   <- MAL (esto es P(X ≥ 13))")
print(f"1 − cdf(11)             = {bien:.6f}   <- BIEN")
print(f"sf(11)                  = {directo:.6f}   <- lo mismo, más corto")
print(f"suma directa desde k=12 = {fuerza:.6f}   <- la verdad de referencia")
print()
print(f"La diferencia entre hacerlo mal y bien es de {abs(bien-mal)*100:.1f} puntos porcentuales.")
print("En un informe, eso es la diferencia entre aprobar y no aprobar un proyecto.")

