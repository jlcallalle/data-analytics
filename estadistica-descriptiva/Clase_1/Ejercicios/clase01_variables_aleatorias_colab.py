"""---
## 05 · Poisson: cuándo sirve y cuándo no

Poisson tiene una firma inconfundible: **el promedio y la varianza son el mismo número, λ**.

Eso la hace fácil de usar y, sobre todo, fácil de **refutar**: si en tus datos la varianza es
mucho más grande que el promedio, Poisson es el modelo equivocado. A eso se le llama
**sobredispersión** (los datos están más desparramados de lo que la fórmula permite).

> **Analogía — gotas de lluvia sobre una loseta.** No sabes cuál gota ni cuándo, pero sí cuántas
> por minuto. Y si la lluvia viene en ráfagas en lugar de caer parejo, la tasa dejó de ser
> constante: eso es sobredispersión.

Para detectarlo hay un chequeo de una sola línea: el **índice de dispersión**, que es
`varianza ÷ promedio`. Si vale cerca de 1, Poisson es plausible. Si vale 4 o 5, no.
"""

# ── CASO A: un call center normal, donde la tasa sí es constante ──────────────
LAMBDA_REAL = 3.5              # 3.5 reclamos por hora, en promedio
horas = 720                    # un mes de operación (30 días × 24 horas)
reclamos = rng.poisson(LAMBDA_REAL, size=horas)

# La mejor estimación de λ es, simplemente, el promedio de los datos.
lambda_hat = reclamos.mean()
varianza   = reclamos.var(ddof=1)

print(f"λ estimado (el promedio) : {lambda_hat:.3f}")
print(f"Varianza observada       : {varianza:.3f}")
print(f"Índice de dispersión     : {varianza/lambda_hat:.3f}   <- cerca de 1 = Poisson sirve")

# Definimos una función para no repetir el mismo gráfico dos veces
def comparar_poisson(datos, titulo, ax):
    '''Dibuja lo observado contra lo que predice Poisson, y muestra el índice de dispersión.'''
    kmax = datos.max()
    ks = np.arange(0, kmax + 1)
    # (datos == k).mean() cuenta qué proporción de los datos vale exactamente k
    obs = np.array([(datos == k).mean() for k in ks])
    esp = stats.poisson.pmf(ks, datos.mean())        # lo que Poisson predeciría

    ax.bar(ks - 0.2, obs, width=0.4, color=AZUL, label="Lo que pasó")
    ax.bar(ks + 0.2, esp, width=0.4, color=ROSA, label="Lo que predice Poisson")
    #      ^^^^^^^^ el −0.2 y +0.2 corren las barras a los lados para que no se tapen

    indice = datos.var(ddof=1) / datos.mean()
    ax.set_title(f"{titulo}\npromedio={datos.mean():.2f} · varianza={datos.var(ddof=1):.2f} · índice={indice:.2f}")
    ax.set_xlabel("reclamos en una hora")
    ax.set_ylabel("proporción de horas")
    ax.legend()

fig, ax = plt.subplots()
comparar_poisson(reclamos, "CASO A — tasa constante", ax)
plt.tight_layout(); plt.show()

