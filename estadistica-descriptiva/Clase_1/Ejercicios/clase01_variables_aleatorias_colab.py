# Se leen así: hubo 109 cuerpos-año con 0 muertes, 65 con 1 muerte, 22 con 2, etc.
bk_muertes = np.array([0, 1, 2, 3, 4])
bk_obs     = np.array([109, 65, 22, 3, 1])

n_cuerpos_anio = bk_obs.sum()                          # 109+65+22+3+1
total_muertes  = (bk_muertes * bk_obs).sum()           # 0×109 + 1×65 + 2×22 + 3×3 + 4×1
bk_lambda      = total_muertes / n_cuerpos_anio         # muertes por cuerpo-año

print(f"Cuerpos-año observados : {n_cuerpos_anio}")
print(f"Muertes en total       : {total_muertes}")
print(f"λ = {total_muertes} ÷ {n_cuerpos_anio} = {bk_lambda:.4f} muertes por cuerpo-año")
print()

